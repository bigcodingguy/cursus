// Headless bot runner: N lifetimes per strategy → metrics report.
//   npm run bots -- --runs 1000            (per strategy; prints the report)
//   npm run bots -- --runs 1000 --write    (also writes docs/balance.md)
//   npm run bots -- --runs 50 --workers 2

import { writeFileSync } from 'node:fs';
import { cpus } from 'node:os';
import { fileURLToPath } from 'node:url';
import { isMainThread, parentPort, Worker, workerData } from 'node:worker_threads';
import { runLifetime, STRATEGIES, type RunMetrics, type StrategyId } from '../src/sim/bots';
import { dateOf } from '../src/sim/calendar';

const STRATS: StrategyId[] = ['orator', 'populist', 'establishment'];

if (!isMainThread) {
  const { jobs } = workerData as { jobs: { seed: number; strategy: StrategyId }[] };
  for (const j of jobs) {
    const { metrics } = runLifetime(j.seed, j.strategy);
    parentPort!.postMessage(metrics);
  }
} else {
  main();
}

function arg(name: string, def: number): number {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? Number(process.argv[i + 1]) : def;
}

async function main() {
  const runs = arg('runs', 100);
  const workers = Math.max(1, Math.min(arg('workers', cpus().length), 8));
  const write = process.argv.includes('--write');
  const jobs = STRATS.flatMap((strategy) => Array.from({ length: runs }, (_, i) => ({ seed: 10000 + i, strategy })));
  const buckets: (typeof jobs)[] = Array.from({ length: workers }, () => []);
  jobs.forEach((j, i) => buckets[i % workers].push(j));
  const results: RunMetrics[] = [];
  const t0 = Date.now();
  const file = fileURLToPath(import.meta.url);
  await Promise.all(
    buckets.map(
      (b) =>
        new Promise<void>((resolve, reject) => {
          const w = new Worker(file, { workerData: { jobs: b } });
          w.on('message', (m: RunMetrics) => {
            results.push(m);
            if (results.length % 100 === 0) process.stderr.write(`  ${results.length}/${jobs.length} runs\n`);
          });
          w.on('error', reject);
          w.on('exit', (code) => (code === 0 ? resolve() : reject(new Error(`worker exited ${code}`))));
        }),
    ),
  );
  const secs = Math.round((Date.now() - t0) / 1000);
  const report = buildReport(results, runs, secs);
  console.log(report);
  if (write) {
    writeFileSync('docs/balance.md', report);
    console.error('wrote docs/balance.md');
  }
}

const pct = (n: number, d: number) => (d ? `${Math.round((100 * n) / d)}%` : '—');
const median = (xs: number[]) => {
  if (!xs.length) return NaN;
  const a = [...xs].sort((x, y) => x - y);
  return a[Math.floor(a.length / 2)];
};

function buildReport(all: RunMetrics[], runs: number, secs: number): string {
  const L: string[] = [];
  L.push('# Balance baseline', '');
  L.push(`Generated by \`npm run bots -- --runs ${runs} --write\` (${all.length} lifetimes, ${secs}s). Seeds 10000–${10000 + runs - 1} per strategy.`, '');
  L.push('Each run plays one bot strategy from Kal. Mart. 133 BC to the end of 100 BC through the same commands as the UI. If the man dies, the bot plays on as his heir.', '');
  L.push('## Career (the first man)', '');
  const ladder = ['none', 'military_tribune', 'quaestor', 'tribune_pleb', 'aedile', 'praetor', 'consul', 'censor'];
  const short: Record<string, string> = { none: 'None', military_tribune: 'Mil. tribune', quaestor: 'Quaestor', tribune_pleb: 'Tribune', aedile: 'Aedile', praetor: 'Praetor', consul: 'Consul', censor: 'Censor' };
  L.push(`| Strategy | ${ladder.map((o) => short[o]).join(' | ')} | Median age at quaestorship | Elections stood (avg) | Laws carried (avg) |`);
  L.push(`|---|${ladder.map(() => '---').join('|')}|---|---|---|`);
  for (const st of STRATS) {
    const r = all.filter((x) => x.strategy === st);
    const q = r.filter((x) => x.quaestorAge !== undefined);
    L.push(`| ${STRATEGIES[st].label} | ${ladder.map((o) => pct(r.filter((x) => x.highest === o).length, r.length)).join(' | ')} | ${median(q.map((x) => x.quaestorAge!))} | ${(r.reduce((a, x) => a + x.electionsContested, 0) / r.length).toFixed(1)} | ${(r.reduce((a, x) => a + x.laws, 0) / r.length).toFixed(2)} |`);
  }
  L.push('', '## The family', '');
  L.push('| Strategy | Heads of the house (avg) | Played as an heir | Extinct | Reached the consulship (any generation) | Family noble by 100 BC |');
  L.push('|---|---|---|---|---|---|');
  for (const st of STRATS) {
    const r = all.filter((x) => x.strategy === st);
    L.push(`| ${st} | ${(r.reduce((a, x) => a + x.generations, 0) / r.length).toFixed(2)} | ${pct(r.filter((x) => x.generations > 1).length, r.length)} | ${pct(r.filter((x) => x.extinct).length, r.length)} | ${pct(r.filter((x) => x.highestLine === 'consul' || x.highestLine === 'censor').length, r.length)} | ${pct(r.filter((x) => x.nobilis).length, r.length)} |`);
  }
  L.push('', '## Risks', '');
  L.push('| Strategy | First man died | Exiled | Bankrupt | Father bankrupt | Father forced to sell land | Debt at end (median) | Trials | Trials won |');
  L.push('|---|---|---|---|---|---|---|---|---|');
  for (const st of STRATS) {
    const r = all.filter((x) => x.strategy === st);
    const trials = r.reduce((a, x) => a + x.trials, 0);
    const won = r.reduce((a, x) => a + x.trialsWon, 0);
    L.push(`| ${st} | ${pct(r.filter((x) => x.died).length, r.length)} | ${pct(r.filter((x) => x.exiled).length, r.length)} | ${pct(r.filter((x) => x.bankrupt).length, r.length)} | ${pct(r.filter((x) => x.fatherBankrupt).length, r.length)} | ${pct(r.filter((x) => x.fatherSoldLand).length, r.length)} | HS ${median(r.map((x) => x.debtEnd)).toLocaleString('en-US')} | ${(trials / r.length).toFixed(1)}/run | ${pct(won, trials)} |`);
  }
  L.push('', '## Wealth (median cash in hand, Kalends of January)', '');
  const years = [133, 130, 127, 124, 121, 118, 115, 112, 109, 106, 103, 100];
  L.push(`| Strategy | ${years.map((y) => `${y}`).join(' | ')} |`);
  L.push(`|---|${years.map(() => '---').join('|')}|`);
  for (const st of STRATS) {
    const r = all.filter((x) => x.strategy === st);
    L.push(`| ${st} | ${years.map((y) => Math.round(median(r.map((x) => x.cashByYear[y] ?? 0)) / 1000) + 'k').join(' | ')} |`);
  }
  L.push('', '## Historical pressures (all strategies)', '');
  L.push('| Event | Fired | Median date |');
  L.push('|---|---|---|');
  const evs: [string, string[]][] = [
    ['Tiberius Gracchus killed', ['capitol', 'capitol_away']],
    ['Tiberius saved on the Capitol', []],
    ['Scipio Aemilianus found dead', ['scipio_death']],
    ['Fregellae destroyed', ['fregellae']],
    ['Gaius Gracchus’s laws', ['gaius_laws']],
    ['Jury law (courts to the equites)', ['jury_law']],
    ['Gaius Gracchus killed', ['aventine', 'aventine_away']],
    ['Micipsa dies; Numidia divided', ['micipsa_dies']],
    ['Cirta massacre', ['cirta']],
    ['War with Jugurtha', ['numidian_war']],
    ['Jugurtha in Rome', ['jugurtha_in_rome']],
    ['The Mamilian court', ['mamilian_verdicts']],
    ['Marius enrolls the head count', ['capite_censi']],
    ['Jugurtha captured', ['jugurtha_captured']],
    ['Noreia (the Cimbri appear)', ['noreia']],
    ['Arausio', ['arausio']],
    ['Aquae Sextiae', ['aquae_sextiae']],
    ['Vercellae', ['vercellae']],
    ['Saturninus killed', ['saturninus_end', 'saturninus_end_away']],
  ];
  for (const [label, ids] of evs) {
    if (!ids.length) continue;
    const days = all.map((x) => ids.map((id) => x.firedDay[id]).find((d) => d !== undefined)).filter((d): d is number => d !== undefined);
    const md = median(days);
    const dd = Number.isFinite(md) ? dateOf(md) : null;
    L.push(`| ${label} | ${pct(days.length, all.length)} | ${dd ? `${dd.dom}/${dd.month + 1}/${dd.yearBC} BC` : '—'} |`);
  }
  L.push('', '## Republic stability (median, 0–100; 65+ debate, 45+ riots, 25+ political murder)', '');
  L.push(`| ${years.map((y) => `${y}`).join(' | ')} |`);
  L.push(`|${years.map(() => '---').join('|')}|`);
  L.push(`| ${years.map((y) => median(all.map((x) => x.stabilityByYear[y] ?? NaN).filter(Number.isFinite))).join(' | ')} |`);
  L.push('', '## Design moments (acceptance test)', '');
  L.push('| Strategy | 1: Capitol, patron among the killers | 2: prosecuting a friend of father’s creditor (median age) | 3: games debt, a vote for sale | 4: omen postpones your election | 5: a late letter | 6: daughter’s suitors | 8: your client vetoes your law | 10: consul in the family, a mask |');
  L.push('|---|---|---|---|---|---|---|---|---|');
  for (const st of STRATS) {
    const r = all.filter((x) => x.strategy === st);
    const m2 = r.filter((x) => x.moments.creditorCase);
    const m = (k: keyof RunMetrics['moments']) => pct(r.filter((x) => x.moments[k]).length, r.length);
    L.push(`| ${st} | ${m('capitolPatron')} | ${pct(m2.length, r.length)} (${median(m2.map((x) => x.moments.creditorCaseAge!)) || '—'}) | ${m('gamesDebt')} | ${m('omen')} | ${m('lateLetter')} | ${m('daughter')} | ${m('clientVeto')} | ${m('nobleMask')} |`);
  }
  L.push('');
  return L.join('\n');
}
